// Unit check: oxygen drains underwater, refills at the surface, drowning kills; 3D movement is accepted.
import { Room } from '../server/room.js';
import * as W from '../public/shared/world.js';
import { PLAYER } from '../public/shared/constants.js';
const conn = { ws: { readyState: 1, send: () => {} }, name: 'S', skin: 0, token: 'x' };
const room = new Room('TEST', { name: 't', max: 4, target: 25 });
const p = room.addPlayer(conn); p.protectUntil = 0;
const lvl = room.level; let pass = true;
const chk = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) pass = false; };
const X = -70, Z = 30, G = W.heightAt(X, Z);
p.x = X; p.z = Z; p.y = G + 2; p.lastState = Date.now() - 100; p.allow = 9;
room.onState(p, { x: X, y: G + 6, z: Z, yaw: 0, pitch: 0, a: 4, e: p.epoch });
chk(Math.abs(p.y - (G + 6)) < 0.01, 'vertical swimming accepted by server');
room.onState(p, { x: X, y: lvl + 5, z: Z, yaw: 0, pitch: 0, a: 4, e: p.epoch });
chk(p.y < lvl, 'cannot rise above the surface');
const o0 = p.o2; for (let i = 0; i < 40; i++) room.tickRelics(Date.now(), lvl);
chk(p.o2 < o0, `oxygen drains at depth (${o0} -> ${p.o2.toFixed(1)})`);
p.y = lvl - 1; for (let i = 0; i < 40; i++) room.tickRelics(Date.now(), lvl);
chk(p.o2 > o0 - 5, 'oxygen refills at the surface');
p.y = G + 6; p.o2 = 0; p.hp = 1; for (let i = 0; i < 20; i++) room.tickRelics(Date.now(), lvl);
chk(!p.alive, 'running out of oxygen drowns the player');
room.destroy(); process.exit(pass ? 0 : 1);
